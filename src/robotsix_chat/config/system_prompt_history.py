"""Historical SHA256 fingerprints of every governed ``agent_instruction`` default.

Every entry in ``docs/system_prompt_changelog.md`` records the SHA256 of the
``Settings.agent_instruction`` default literal at that version. That changelog
lives under ``docs/`` and is **not** shipped inside the runtime container image
(the Dockerfile copies only ``src/``), so the boot-time reconciliation in
:mod:`robotsix_chat.config.settings` cannot read it at runtime. This module is
the shipped, code-side mirror of those fingerprints.

A stored ``agent_instruction`` whose SHA256 is in this set is a *former default*
that a config volume froze in place — it must be auto-upgraded to the current
code default at boot. A stored value matching **no** recorded fingerprint is a
genuine operator customization and is kept (with a boot warning).

``tests/config/test_system_prompt_governance.py`` asserts this set is exactly
the set of SHA256 records in ``docs/system_prompt_changelog.md`` — so bumping
the prompt (which adds a changelog entry + SHA) fails CI until the new hash is
mirrored here. Keep this file sorted; append new hashes in the same pass that
bumps ``SYSTEM_PROMPT_VERSION``.
"""

